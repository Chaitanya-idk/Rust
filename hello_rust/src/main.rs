fn main() {
    //print!() and println!() ! inidcates macro functions, not completely function.
    println!("Hello, world!");
    //variables can be initialized with let keyword.
    // variables are not mutable, we use "mut" keyword to enable editing or changing.

    let mut x = 5;
    println!("{}", x);
    x = 10;
    println!("{}", x);

    //datatypes
}
